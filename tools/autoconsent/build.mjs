// Builds the cookie banner resources in Packages/PlainKit/Sources/ContentBlocking/Resources/CookieBanners
// from the pinned @duckduckgo/autoconsent (MPL-2.0). Run: `cd tools/autoconsent && npm ci && npm run build`.
//
// Output:
// - autoconsent.js: entry.js and the autoconsent engine as one minified script (the app injects it
//   into main frames at document start, and into subframes that a rule targets).
// - rules.json: autoconsent's compact rules, split so the app never sends a frame rules it can't use:
//   `generic` (every main frame gets these) and `specific` (one self-contained ruleset per rule with an
//   address pattern, with flags for main frame and subframe), as autoconsent's own
//   `filterCompactRules` would pick them.
// - MPL-2.0.txt and NOTICE.txt: the license and where the source of this exact version is.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../../Packages/PlainKit/Sources/ContentBlocking/Resources/CookieBanners');
const packageDir = join(here, 'node_modules/@duckduckgo/autoconsent');
const version = JSON.parse(readFileSync(join(packageDir, 'package.json'), 'utf8')).version;
mkdirSync(out, { recursive: true });

await build({
    entryPoints: [join(here, 'entry.js')],
    bundle: true,
    minify: true,
    format: 'iife',
    target: 'safari18',
    legalComments: 'none',
    banner: {
        js: `// Plain cookie banners: DuckDuckGo autoconsent ${version} (MPL-2.0, https://github.com/duckduckgo/autoconsent/tree/v${version}) and Plain's bridge (AGPL-3.0-only). Generated by tools/autoconsent; do not edit.`,
    },
    outfile: join(out, 'autoconsent.js'),
});

// Compact rule format (autoconsent lib/encoding.ts): each rule is
// [minVersion, name, cosmetic, urlPattern, runContext, prehide[], detectCmp[], detectPopup[], optOut[], test[], extra],
// and every selector or string in a step is an index into the shared string table `s`.
const compact = JSON.parse(readFileSync(join(packageDir, 'rules/compact-rules.json'), 'utf8'));
const { v, s, r, index } = compact;
const stringKeys = ['e', 'v', 'c', 'k', 'w', 'wv', 'h', 'cc'];

function remapSteps(steps, map) {
    return steps.map((step) => {
        const copy = { ...step };
        for (const key of stringKeys) {
            if (copy[key] !== undefined) copy[key] = map(copy[key]);
        }
        if (copy.if) copy.if = remapSteps([copy.if], map)[0];
        if (copy.then) copy.then = remapSteps(copy.then, map);
        if (copy.else) copy.else = remapSteps(copy.else, map);
        if (copy.any) copy.any = remapSteps(copy.any, map);
        return copy;
    });
}

/** One rule with only the strings it uses, renumbered from 0. */
function selfContained(rule) {
    const strings = [];
    const ids = new Map();
    const map = (id) => {
        if (!ids.has(id)) {
            ids.set(id, strings.length);
            strings.push(s[id]);
        }
        return ids.get(id);
    };
    const copy = [...rule];
    copy[5] = rule[5].map(map);
    for (const i of [6, 7, 8, 9]) copy[i] = remapSteps(rule[i], map);
    return { v, s: strings, r: [copy] };
}

// runContext is two digits, main frame then subframe, each 0 false / 1 true / 2 unset; one digit
// means main is unset. Same test as autoconsent's shouldRunRuleInContext.
const runsInMain = (code) => code !== 1;
const runsInFrame = (code) => ![20, 22, 10, 12].includes(code);

const generic = { v, s: s.slice(0, index.genericStringEnd), r: r.slice(...index.genericRuleRange) };
const specific = r.slice(...index.specificRuleRange).map((rule) => ({
    p: rule[3],
    m: runsInMain(rule[4]),
    f: runsInFrame(rule[4]),
    r: JSON.stringify(selfContained(rule)),
}));
if (specific.some((entry) => !entry.p)) throw new Error('a specific rule has no address pattern');

writeFileSync(
    join(out, 'rules.json'),
    JSON.stringify({ version, generic: JSON.stringify(generic), specific }) + '\n',
);
copyFileSync(join(packageDir, 'LICENSE'), join(out, 'MPL-2.0.txt'));
writeFileSync(
    join(out, 'NOTICE.txt'),
    `autoconsent.js and rules.json contain DuckDuckGo autoconsent ${version}, unmodified,
Copyright (c) DuckDuckGo, Inc., licensed under the Mozilla Public License 2.0 (MPL-2.0.txt).
Source code of this exact version: https://github.com/duckduckgo/autoconsent/tree/v${version}
and the npm package @duckduckgo/autoconsent@${version}.
Plain's bridge (tools/autoconsent/entry.js) and the build (tools/autoconsent/build.mjs) are
AGPL-3.0-only, part of Plain; MPL-2.0 section 3.3 allows the combination (AGPL-3.0 is a
Secondary License).
`,
);
console.log(`autoconsent ${version}: ${generic.r.length} generic rules, ${specific.length} specific rules`);
